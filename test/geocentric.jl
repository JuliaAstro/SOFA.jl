####    Test Astronomy Geocentric Coordinates    ####

@test all(abs.(values(SOFA.eform(:WGS84)) .- (6378137.0, 0.3352810664747480720e-2)) .<= 1e-12)

@test all(abs.(values(SOFA.eform(:GRS80)) .- (6378137.0, 0.3352810681182318935e-2)) .<= 1e-12)

@test all(abs.(values(SOFA.eform(:WGS72)) .- (6378135.0, 0.3352779454167504862e-2)) .<= 1e-12)

@test all(abs.(values(SOFA.gc2gd(:WGS84, [2e6, 3e6, 5.244e6])) .-
               (0.9827937232473290680, 0.97160184819075459, 331.4172461426059892)) .<= 1e-8)

@test all(abs.(values(SOFA.gc2gd(:GRS80, [2e6, 3e6, 5.244e6])) .-
               (0.9827937232473290680, 0.97160184820607853, 331.41731754844348)) .<= 1e-8)

@test all(abs.(values(SOFA.gc2gd(:WGS72, [2e6, 3e6, 5.244e6])) .-
               (0.9827937232473290680, 0.9716018181101511937, 333.2770726130318123)) .<= 1e-8)

@test all(abs.(values(SOFA.gc2gde(6378136.0, 0.0033528, [2e6, 3e6, 5.244e6])) .-
               (0.9827937232473290680, 0.9716018377570411532, 332.36862495764397)) .<= 1e-8)

